"""
Sentinel AI - Risk Prioritizer

Ranks cybersecurity vulnerabilities using
the risk scores generated by Risk Engine V2.
"""

import pandas as pd


class RiskPrioritizer:
    """Prioritize vulnerabilities by risk score."""

    REQUIRED_COLUMNS = [
        "cveID",
        "risk_score",
        "risk_level"
    ]

    def prioritize(self, data):
        """Return vulnerabilities ordered by descending risk."""

        missing = [
            column for column in self.REQUIRED_COLUMNS
            if column not in data.columns
        ]

        if missing:
            raise ValueError(
                f"Missing required columns: {missing}"
            )

        result = data.copy()

        if result["cveID"].isna().any():
            raise ValueError("CVE identifiers cannot be missing.")

        if result["cveID"].duplicated().any():
            raise ValueError("Duplicate CVE identifiers detected.")

        result["risk_score"] = pd.to_numeric(
            result["risk_score"],
            errors="coerce"
        )

        if result["risk_score"].isna().any():
            raise ValueError("Risk scores contain invalid values.")

        if not result["risk_score"].between(0, 100).all():
            raise ValueError("Risk scores must be between 0 and 100.")

        result = result.sort_values(
            by=["risk_score", "cveID"],
            ascending=[False, True]
        ).reset_index(drop=True)

        result.insert(
            0,
            "risk_priority",
            range(1, len(result) + 1)
        )

        return result

    def get_top_priority(self, data, n=10):
        """Return the N highest-priority vulnerabilities."""

        if not isinstance(n, int) or n < 1:
            raise ValueError("n must be a positive integer.")

        ranked = self.prioritize(data)

        return ranked.head(n).copy()
